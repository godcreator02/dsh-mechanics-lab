/**
 * 干活的插件 —— **清理写对**的那一版。
 *
 * 三件事：
 *   1. 报上任，带一个只属于这次挂载的标记
 *   2. 起一个要跑好几秒的活儿，开始和结束各报一次（都带同一个标记）
 *   3. provide 一个服务出去，让旁观者能查
 *
 * 那个标记是整个实验的地基：重载之后如果收到**旧标记**的上报，
 * 就说明旧的那份还在跑 —— 没有标记的话，两份并存和一份正常跑
 * 在事件流里长得一模一样。
 *
 * 「清理写对」指的是最后那段 `ctx.effect`：它把定时器的取消登记给框架，
 * 拆这个条目时框架会替你把它停掉。对照组 `busy-leaky.mjs` 少的就是这一段。
 */

const 标记 = "clean-" + Math.random().toString(36).slice(2, 6);
const 干活毫秒 = 5000;

export const inject = ["labObserver"];

export function apply(ctx, config) {
  const say = ctx.labObserver.for(ctx);

  say("我上任了", { 标记, 版本: "第一版" });

  // 一个要跑好几秒的活儿。5 秒是故意的——留足窗口让人在它干到一半时改文件。
  say("开始干活", { 标记 });
  const 定时器 = setTimeout(() => {
    // 这一句能不能报出来，就是「进行中的操作被不被中断」的答案
    say("干完了", { 标记 });
  }, 干活毫秒);

  // provide 出去的东西也带标记：旁观者查到的是哪一份，一目了然
  ctx.provide("busyJob", { 标记, 版本: "第一版" });

  // ── 清理写对的关键：把取消动作登记给框架 ──────────────────────
  // 拆这个条目时框架会调用返回的这个函数，定时器随之取消，
  // 那句「干完了」就永远不会出现。
  ctx.effect(() => () => {
    clearTimeout(定时器);
    say("我被拆了，定时器一并取消", { 标记 });
  }, "busy-clean: 干活定时器");
}
